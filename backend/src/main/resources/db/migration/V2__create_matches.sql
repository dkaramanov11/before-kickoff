CREATE TABLE matches (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         external_api_id BIGINT,
                         home_team_id BIGINT NOT NULL,
                         away_team_id BIGINT NOT NULL,
                         kickoff_at TIMESTAMP WITH TIME ZONE NOT NULL,
                         status VARCHAR(30) NOT NULL,
                         matchday INTEGER,
                         home_score INTEGER,
                         away_score INTEGER,

                         CONSTRAINT uq_matches_external_api_id
                             UNIQUE (external_api_id),

                         CONSTRAINT fk_matches_home_team
                             FOREIGN KEY (home_team_id) REFERENCES teams(id),

                         CONSTRAINT fk_matches_away_team
                             FOREIGN KEY (away_team_id) REFERENCES teams(id),

                         CONSTRAINT chk_matches_different_teams
                             CHECK (home_team_id <> away_team_id),

                         CONSTRAINT chk_matches_home_score
                             CHECK (home_score >= 0),

                         CONSTRAINT chk_matches_away_score
                             CHECK (away_score >= 0)
);

CREATE INDEX idx_matches_kickoff_at
    ON matches(kickoff_at);