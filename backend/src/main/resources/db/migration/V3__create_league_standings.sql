CREATE TABLE league_standings (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  competition_code VARCHAR(10) NOT NULL,
                                  competition_name VARCHAR(150) NOT NULL,
                                  season_start_year INTEGER NOT NULL,
                                  last_synced_at TIMESTAMP WITH TIME ZONE NOT NULL,

                                  CONSTRAINT uq_league_standings_competition
                                      UNIQUE (competition_code)
);

CREATE TABLE league_standing_entries (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         league_standing_id BIGINT NOT NULL,
                                         team_id BIGINT NOT NULL,
                                         position INTEGER NOT NULL,
                                         played_games INTEGER NOT NULL,
                                         won INTEGER NOT NULL,
                                         draw INTEGER NOT NULL,
                                         lost INTEGER NOT NULL,
                                         goals_for INTEGER NOT NULL,
                                         goals_against INTEGER NOT NULL,
                                         goal_difference INTEGER NOT NULL,
                                         points INTEGER NOT NULL,

                                         CONSTRAINT fk_standing_entries_standing
                                             FOREIGN KEY (league_standing_id)
                                                 REFERENCES league_standings (id),

                                         CONSTRAINT fk_standing_entries_team
                                             FOREIGN KEY (team_id)
                                                 REFERENCES teams (id),

                                         CONSTRAINT uq_standing_entries_team
                                             UNIQUE (league_standing_id, team_id),

                                         CONSTRAINT uq_standing_entries_position
                                             UNIQUE (league_standing_id, position),

                                         CONSTRAINT chk_standing_entries_position
                                             CHECK (position > 0),

                                         CONSTRAINT chk_standing_entries_played_games
                                             CHECK (played_games >= 0),

                                         CONSTRAINT chk_standing_entries_results
                                             CHECK (won >= 0 AND draw >= 0 AND lost >= 0),

                                         CONSTRAINT chk_standing_entries_goals
                                             CHECK (goals_for >= 0 AND goals_against >= 0)
);